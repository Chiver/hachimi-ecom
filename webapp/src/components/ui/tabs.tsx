  React.ElementRef<typeof TabsPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof TabsPrimitive.Trigger>
>(({ className, ...props }, ref) => (
  <TabsPrimitive.Trigger
    ref={ref}
    className={cn(
      "inline-flex items-center px-4 py-2 text-sm font-medium text-[var(--color-text-dim)] transition-colors hover:text-[var(--color-text)] focus-visible:outline-none disabled:pointer-events-none disabled:opacity-50",
      "data-[state=active]:text-[var(--color-text)] data-[state=active]:border-b-2 data-[state=active]:border-[var(--color-primary)] data-[state=active]:-mb-px",
      className,
    )}
    {...props}
  />
));
TabsTrigger.displayName = TabsPrimitive.Trigger.displayName;

